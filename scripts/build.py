def tx(d: dict, field: str, lang: str) -> str:
    """taxonomy 条目的显示文字：英文版优先取 xxx_en，没有就用中文。"""
    return (lang == "en" and d.get(f"{field}_en")) or d.get(field, "")


def text(s: dict, field: str, lang: str) -> str:
    return (lang == "en" and s.get(f"{field}_en")) or s.get(field, "")


def gh_url(repo: str) -> str:
    return f"https://github.com/{repo}"


# 仓库名重复的项目（不同作者的同名仓库）显示成 owner/name，免得名单里分不清
DUP_NAMES: set[str] = set()


def display_name(s: dict) -> str:
    if s.get("name"):
        return s["name"]
    name = s["repo"].split("/", 1)[1]
    return s["repo"] if name.lower() in DUP_NAMES else name


def fmt_stars(n: int | None) -> str:
    if n is None:
        return "—"
    return f"{n / 1000:.1f}k".replace(".0k", "k") if n >= 1000 else str(n)


def cell(t: str) -> str:
    return t.replace("|", "\\|").replace("\n", " ")


def sort_key(s: dict, meta: dict):
    stars = meta.get(s["repo"], {}).get("stars", -1)
    return (s.get("tier") != "featured", -stars, display_name(s).lower())


def status_mark(m: dict, ref: dt.date | None) -> str:
    if m.get("status") == "missing":
        return " ⚠️"
    if m.get("archived"):
        return " 📦"
    if ref and m.get("pushed_at") and (ref - dt.date.fromisoformat(m["pushed_at"])).days > STALE_DAYS:
        return " 💤"
    return ""


def install_cmd(s: dict) -> str | None:
    if s.get("install"):
        return s["install"]
    if s["format"] == "skill":
        return f"npx skills add {s['repo']}"
    return None


def by_stars(items, meta: dict) -> list[dict]:
    return sorted(items, key=lambda s: -meta.get(s["repo"], {}).get("stars", -1))


def links(items) -> str:
    return " · ".join(f"[{display_name(s)}]({gh_url(s['repo'])})" for s in items)


class Page:
    """一种语言的 README / METHODS 渲染。"""

    def __init__(self, lang: str, taxonomy: dict, skills: list[dict], packs: list[dict], meta_all: dict):
        self.lang, self.ui = lang, UI[lang]
        self.taxonomy, self.skills, self.packs = taxonomy, skills, packs
        self.meta_all = meta_all
        self.meta = meta_all.get("repos", {})
        self.ref = dt.date.fromisoformat(meta_all["fetched_at"]) if meta_all.get("fetched_at") else None
        self.groups = taxonomy["groups"]
        self.methods = taxonomy["methods"]
        self.grouped = {k: sorted((s for s in skills if s["group"] == k), key=lambda s: sort_key(s, self.meta))
                        for k in self.groups}
        self.indexed = [s for s in skills if self.groups[s["group"]].get("indexed", True)]

    def n(self, x) -> str:
        return self.ui["n"].format(x)

    def stars_suffix(self, s: dict) -> str:
        stars = self.meta.get(s["repo"], {}).get("stars")
        return f" ★{fmt_stars(stars)}" if stars is not None else ""

    # ── 条目 ──
    def meta_line(self, s: dict, m: dict) -> str:
        ui = self.ui
        sub = [ui["updated"].format(m.get("pushed_at") or "—") + status_mark(m, self.ref)]
        if s["format"] in ui["format_badge"]:
            sub.append(ui["format_badge"][s["format"]])
        sub.append(ui["lang_label"][s["lang"]])
        if m.get("skill_count", 0) > 1:
            sub.append(ui["n_skills"].format(f"{m['skill_count']}{'+' if m.get('skill_count_truncated') else ''}"))
        if m.get("license"):
            sub.append(m["license"])
        return " · ".join(sub)

    def entry(self, s: dict) -> str:
        m = self.meta.get(s["repo"], {})
        star = "🌟 " if s.get("tier") == "featured" else ""
        name = f"{star}**[{display_name(s)}]({gh_url(s['repo'])})** · ★ {fmt_stars(m.get('stars'))}"
        method_text = " · ".join(tx(mt, "short", self.lang) for k, mt in self.methods.items() if k in s["methods"])
        body = (cell(text(s, "desc", self.lang)) + f"<br><sub>{self.ui['methods_line']}{method_text}</sub>"
                f"<br><sub>{self.meta_line(s, m)}</sub>")
        if s.get("note"):
            body += f"<br><sub>💡 {cell(text(s, 'note', self.lang))}</sub>"
        return f"- {name}<br>{body}"

    # ── README 各节 ──
    def render_group(self, key: str, group: dict, items: list[dict]) -> list[str]:
        out = [f'<a id="group-{key}"></a>', f"### {tx(group, 'label', self.lang)}", ""]
        if tx(group, "intro", self.lang):
            out += [tx(group, "intro", self.lang), ""]
        families = [(name, [s for s in items if s["format"] in formats])
                    for name, formats in zip(self.ui["families"], FORMAT_FAMILIES)]
        families = [(name, fam) for name, fam in families if fam]
        for name, fam in families:
            if len(families) > 1:
                out += [f"#### {name}{self.n(len(fam))}", ""]
            for s in fam:
                out += [self.entry(s), ""]

        cmds = [(display_name(s), install_cmd(s)) for s in items if install_cmd(s)]
        if cmds:
            out += ["", f"<details><summary>{self.ui['install']}</summary>", "", "```bash", self.ui["install_note"]]
            for name, cmd in cmds:
                out += [f"# {name}", cmd]
            out += ["```", "", "</details>"]
        return out + [""]

    def new_entries(self) -> list[dict]:
        if self.ref is None:
            return []
        def age(s):
            seen = self.meta.get(s["repo"], {}).get("first_seen")
            return (self.ref - dt.date.fromisoformat(seen)).days if seen else None
        hits = [s for s in self.skills if (a := age(s)) is not None and 0 <= a < NEW_DAYS]
        return sorted(hits, key=lambda s: (age(s), -self.meta.get(s["repo"], {}).get("stars", -1)))

    def render_new(self, items: list[dict]) -> list[str]:
        ui = self.ui
        out = ['<a id="new"></a>', f"## {ui['new']}", ""]
        if not items:
            return out + [ui["new_none"], ""]
        out += [ui["new_some"].format(days=NEW_DAYS, n=len(items)), ""]
        for s in items[:NEW_SHOWN]:
            out.append(f"- [{display_name(s)}]({gh_url(s['repo'])}){self.stars_suffix(s)}{ui['colon']}"
                       f"{cell(text(s, 'desc', self.lang))}")
        if len(items) > NEW_SHOWN:
            out.append(ui["new_more"].format(n=len(items) - NEW_SHOWN))
        return out + [""]

    def render_featured(self, items: list[dict]) -> list[str]:
        if not items:
            return []
        ui = self.ui
        out = ['<a id="featured"></a>', f"## {ui['featured']}", "", ui["featured_intro"], ""]
        for s in items:
            group = tx(self.groups[s["group"]], "label", self.lang)
            out.append(f"- [{display_name(s)}]({gh_url(s['repo'])}){self.stars_suffix(s)} · {group}{ui['colon']}"
                       f"{cell(text(s, 'desc', self.lang))}")
        return out + [""]

    def render_packs(self) -> list[str]:
        ui = self.ui
        by_repo = {s["repo"].lower(): s for s in self.skills}
        out = ['<a id="packs"></a>', f"## {ui['packs']}", "", ui["packs_note"], ""]
        for p in self.packs:
            chain = " → ".join(
                f"[{display_name(by_repo[r.lower()])}]({gh_url(by_repo[r.lower()]['repo'])})" for r in p["repos"]
            )
            out += [f"- **{p['name']}**{ui['colon']}{p['goal']}",
                    f"  - {ui['pack_combo']}{ui['colon']}{chain}",
                    f"  - {ui['pack_why']}{ui['colon']}{p['why']}"]
        return out + [""]

    def method_count(self, key: str) -> int:
        return sum(key in s["methods"] for s in self.indexed)

    def readme(self) -> str:
        ui, lang = self.ui, self.lang
        suffix = ".en" if lang == "en" else ""
        header = (TEMPLATES / f"header{suffix}.md").read_text(encoding="utf-8")
        header = (header.replace("{{count}}", str(len(self.indexed)))
                        .replace("{{skills}}", str(sum(s["format"] in ("skill", "prompts") for s in self.skills)))
                        .replace("{{tools}}", str(sum(s["format"] in ("harness", "app") for s in self.skills)))
                        .replace("{{research}}", str(sum(s["format"] == "research" for s in self.skills)))
                        .replace("{{updated}}", self.meta_all.get("fetched_at") or "—"))

        new = self.new_entries()
        featured = [s for k in self.groups for s in self.grouped[k] if s.get("tier") == "featured"]
        toc = [f"## {ui['toc']}", "", f"- [{ui['new']}](#new){self.n(len(new))}"]
        toc += [f"- [{ui['featured']}](#featured){self.n(len(featured))}"] if featured else []
        toc += [f"- [{ui['packs']}](#packs)"] if self.packs else []
        toc += [f"- [{ui['by_group']}](#by-group)"]
        toc += [f"  - [{tx(g, 'label', lang)}](#group-{k}){self.n(len(self.grouped[k]))}"
                for k, g in self.groups.items() if self.grouped[k]]
        toc += [f"- [{ui['by_method']}](#by-method)", f"- [{ui['resources']}](#resources)", f"- [{ui['badge']}](#badge)", ""]

        body = ['<a id="by-group"></a>', f"## {ui['by_group']}", ""]
        for k, g in self.groups.items():
            if self.grouped[k]:
                body += self.render_group(k, g, self.grouped[k])

        # 方法指南篇幅大，单独生成 METHODS.md，README 只放各方法的入口
        method_links = ['<a id="by-method"></a>', f"## {ui['by_method']}", "", ui["by_method_intro"].format(f=ui["methods"]), ""]
        for k, mt in self.methods.items():
            if n := self.method_count(k):
                method_links.append(f"- [{tx(mt, 'label', lang)}]({ui['methods']}#method-{k}){self.n(n)}")

        return "\n".join([
            ui["gen_note"],
            "",
            header.rstrip(),
            "",
            *toc,
            *self.render_new(new),
            *self.render_featured(featured),
            *(self.render_packs() if self.packs else []),
            *body,
            *method_links,
            "",
            (TEMPLATES / f"footer{suffix}.md").read_text(encoding="utf-8").rstrip(),
            "",
        ])

    def methods_page(self) -> str:
        ui, lang = self.ui, self.lang
        used = [(k, mt, self.method_count(k)) for k, mt in self.methods.items() if self.method_count(k)]
        out = [ui["gen_note"], "", f"# {ui['guide_title']}", "", ui["guide_switch"], "",
               ui["guide_intro"].format(n=len(used), readme=ui["readme"]), ""]
        out += [f"- [{tx(mt, 'label', lang)}](#method-{k}){self.n(n)}" for k, mt, n in used] + [""]
        for k, mt, n in used:
            out += [f'<a id="method-{k}"></a>', f"## {tx(mt, 'label', lang)}{self.n(n)}", ""]
            guide = TEMPLATES / "methods" / (f"{k}.en.md" if lang == "en" else f"{k}.md")
            if guide.exists():
                out += [guide.read_text(encoding="utf-8").strip(), ""]
            out += [f"**{ui['projects']}**{self.n(n)}", ""]
            hits = by_stars((s for s in self.indexed if k in s["methods"]), self.meta)
            for name, formats in zip(ui["families"], FORMAT_FAMILIES):
                items = [s for s in hits if s["format"] in formats]
                if items:
                    out.append(f"- {name}{self.n(len(items))}{ui['colon']}{links(items)}")
            out += [""]
        return "\n".join(out).rstrip() + "\n"


def render_catalog(taxonomy: dict, skills: list[dict], meta_all: dict) -> str:
    """给 agent 和脚本用的机器可读索引：一行一个项目，方便 grep。"""
    meta = meta_all.get("repos", {})
    groups = taxonomy["groups"]

    def labels(section: dict) -> dict:
        return {k: {"label": v["label"], "label_en": v.get("label_en", "")} for k, v in section.items()}

    head = {
        "name": "awesome-story-skills",
        "url": REPO_URL,
        "updated": meta_all.get("fetched_at"),
        "groups": labels(groups),
        "methods": labels(taxonomy["methods"]),
        "formats": taxonomy["formats"],
    }
    rows = []
    for k in groups:
        for s in sorted((s for s in skills if s["group"] == k), key=lambda s: sort_key(s, meta)):
            m = meta.get(s["repo"], {})
            row = {
                "repo": s["repo"], "name": display_name(s), "group": s["group"], "methods": s["methods"],
                "format": s["format"], "lang": s["lang"], "agents": s.get("agents"),
                "featured": s.get("tier") == "featured" or None,
                "desc": s["desc"], "desc_en": s.get("desc_en"), "note": s.get("note"), "note_en": s.get("note_en"),
                "install": install_cmd(s), "stars": m.get("stars"), "pushed_at": m.get("pushed_at"),
                "archived": m.get("archived") or None, "license": m.get("license"),
            }
            rows.append(json.dumps({k: v for k, v in row.items() if v not in (None, [], "")}, ensure_ascii=False))
    head_json = json.dumps(head, ensure_ascii=False, indent=1)
    return head_json[:-2] + ',\n "entries": [\n' + ",\n".join(rows) + "\n ]\n}\n"


def render(taxonomy: dict, skills: list[dict], packs: list[dict], meta_all: dict) -> dict:
    names = [s["repo"].split("/", 1)[1].lower() for s in skills if not s.get("name")]
    DUP_NAMES.clear()
    DUP_NAMES.update(n for n in names if names.count(n) > 1)
    out = {}
    for lang in UI:
        page = Page(lang, taxonomy, skills, packs, meta_all)
        out[ROOT / UI[lang]["readme"]] = page.readme()
        out[ROOT / UI[lang]["methods"]] = page.methods_page()
    out[CATALOG] = render_catalog(taxonomy, skills, meta_all)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="只检查生成文件是否最新")
    ap.add_argument("--validate", action="store_true", help="只校验数据")
    args = ap.parse_args()

    taxonomy, skills, packs, _ = load_valid()
    if args.validate:
        print(f"数据校验通过：{len(skills)} 个项目，{len(packs)} 个组合。")
        return

    meta_all = load_meta()
    unfetched = [s["repo"] for s in skills if s["repo"] not in meta_all.get("repos", {})]
    if unfetched:
        print(f"提示：{len(unfetched)} 个仓库还没有元数据，先运行 scripts/refresh.py --only {' '.join(unfetched)}",
              file=sys.stderr)
    untranslated = [s["repo"] for s in skills if not s.get("desc_en")]
    if untranslated:
        print(f"提示：{len(untranslated)} 个项目缺 desc_en，英文版暂用中文简介：{' '.join(untranslated[:10])}"
              f"{' …' if len(untranslated) > 10 else ''}", file=sys.stderr)

    outputs = render(taxonomy, skills, packs, meta_all)
    names = "、".join(p.name for p in outputs)
    if args.check:
        stale = [p.name for p, t in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            sys.exit(f"{'、'.join(stale)} 不是最新的，请运行 python3 scripts/build.py")
        print(f"{names} 已是最新。")
        return
    for path, t in outputs.items():
        path.write_text(t, encoding="utf-8")
    print(f"已生成 {names}：{len(skills)} 个项目。")


if __name__ == "__main__":
    main()
